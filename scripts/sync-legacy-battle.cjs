#!/usr/bin/env node
'use strict';
// Wrap the immutable browser compatibility factory as an isolated Worker module.
// Its source is pinned to v82; never regenerate it from the current game DATA.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..'),source=fs.readFileSync(path.join(root,'legacy-battle-v82.js'),'utf8');
const hash=crypto.createHash('sha256').update(source).digest('hex');
const FROZEN_SHA256='5710c28068480a05bc3e7d0f12bc8268febb5b94c94b490d6e87a3019b1d94dc';
if(hash!==FROZEN_SHA256)throw Error('Frozen v82 battle source has changed; preserve the published combat rules.');
const output=`// Generated by scripts/sync-legacy-battle.cjs. Do not edit by hand.
// Frozen browser compatibility SHA-256: ${hash}
const globalThis={LT:{}};
${source}
export default globalThis.LT.LegacyBattles;
`;
const target=path.join(root,'server','battle-legacy-v82.mjs');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw Error('Legacy battle module is stale. Run node scripts/sync-legacy-battle.cjs');
  console.log('Frozen v82 battle module matches the browser compatibility factory.');
}else{fs.writeFileSync(target,output);console.log(`Generated frozen v82 battle module (${Buffer.byteLength(output)} bytes).`);}
