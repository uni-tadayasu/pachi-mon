#!/usr/bin/env node
'use strict';
// Literal shared source keeps Worker and browser combat behavior identical.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..'),html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const blocks=[...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)];
const duel=blocks.find(match=>!(/\bsrc=/.test(match[1]))&&match[2].includes('deterministic, save-independent rental-team duels'))?.[2].trim();
if(!duel)throw Error('Shared human-duel source was not found');
const model=fs.readFileSync(path.join(root,'kasai-live-model.js'),'utf8').trim(),shared=duel+'\n\n'+model;
const hash=crypto.createHash('sha256').update(shared).digest('hex');
const version=model.match(/\bconst VERSION=('[-a-zA-Z0-9]+');/)?.[1];
if(!version)throw Error('Static live rule version was not found');
const output=`// Generated by scripts/sync-kasai-live.cjs. Do not edit by hand.
// Shared human-duel / live-model SHA-256: ${hash}
import {createReplayRuntime} from './kasai-replay.mjs';
import legacyBattles from './battle-legacy-v82.mjs';
function createLiveRuntime(){
  const globalThis={LT:createReplayRuntime()};
  globalThis.LT.LegacyBattles=legacyBattles;
${shared}
  return globalThis.LT.KasaiLiveRules;
}
// Initialize the shared world only when a live battle actually needs it.
let cachedRules;
function liveRules(){return cachedRules||(cachedRules=createLiveRuntime());}
export const LIVE_RULES_VERSION=${version};
export const createLiveBattle=(challengerParty,kasaiParty,seed,names)=>liveRules().create(challengerParty,kasaiParty,seed,names);
export const validateLiveOrders=(state,side,orders)=>liveRules().validate(state,side,orders);
export const resolveLiveRound=(state,orders)=>liveRules().resolve(state,orders);
`;
const target=path.join(root,'server','kasai-live-engine.mjs');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw Error('Live battle source is stale. Run node scripts/sync-kasai-live.cjs');
  console.log('Kasai live battle source matches the shipped browser rules.');
}else{fs.writeFileSync(target,output);console.log(`Generated live Kasai rules (${Buffer.byteLength(output)} bytes).`);}
