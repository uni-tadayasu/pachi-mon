#!/usr/bin/env node
'use strict';
// Generate the Worker module from the literal rules that the browser ships.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..'),html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const blocks=[...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)];
const duel=blocks.find(match=>!(/\bsrc=/.test(match[1]))&&match[2].includes('deterministic, save-independent rental-team duels'))?.[2].trim();
if(!duel)throw Error('Shared rental duel source was not found');
const model=fs.readFileSync(path.join(root,'ranked-rules.js'),'utf8').trim(),shared=duel+'\n\n'+model;
const hash=crypto.createHash('sha256').update(shared).digest('hex');
const version=model.match(/\bconst VERSION=('[-a-zA-Z0-9]+');/)?.[1];
const legacyVersion=model.match(/\bconst LEGACY_VERSION=('[-a-zA-Z0-9]+');/)?.[1];
if(!version)throw Error('Static ranked rule version was not found');
const output=`// Generated by scripts/sync-ranked.cjs. Do not edit by hand.
// Shared rental-duel / ranked-model SHA-256: ${hash}
import {createReplayRuntime} from './kasai-replay.mjs';
function createRankedRuntime(){
  const globalThis={LT:createReplayRuntime()};
${shared}
  return globalThis.LT.RankedRules;
}
let cachedRules;
function rankedRules(){return cachedRules||(cachedRules=createRankedRuntime());}
export const RANKED_RULES_VERSION=${version};
export const RANKED_COMPATIBLE_VERSIONS=Object.freeze([${version}${legacyVersion?','+legacyVersion:''}]);
export const rankedRulesInfo=()=>rankedRules().info();
export const rankForRating=rating=>rankedRules().rankForRating(rating);
export const normalizeRankedTeam=team=>rankedRules().normalizeTeam(team);
export const rankedPreviewMember=mon=>rankedRules().previewMember(mon);
export const validateRankedTeam=team=>rankedRules().validateTeam(team);
export const createRankedBattle=(team0,team1,seed,names)=>rankedRules().create(team0,team1,seed,names);
export const validateRankedOrders=(state,side,orders)=>rankedRules().validate(state,side,orders);
export const resolveRankedRound=(state,orders)=>rankedRules().resolve(state,orders);
`;
const target=path.join(root,'server','ranked-engine.mjs');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw Error('Ranked rules are stale. Run node scripts/sync-ranked.cjs');
  console.log('Ranked battle source matches the shipped browser rules.');
}else{fs.writeFileSync(target,output);console.log(`Generated ranked rules (${Buffer.byteLength(output)} bytes).`);}
