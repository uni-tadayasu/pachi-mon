#!/usr/bin/env node
'use strict';
// Cloudflare Workers cannot evaluate strings as JavaScript. Ship the exact
// browser data and Engine as literal module source, with a private LT namespace.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..'),html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const blocks=[];
for(const match of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)){
  if(/\bsrc=|application\/ld\+json/.test(match[1]))continue;
  blocks.push(match[2].trim());
  if(match[2].includes('LT.Engine=Engine;'))break;
}
if(!blocks.at(-1)?.includes('LT.KasaiRules=Object.freeze'))throw Error('Kasai Engine source was not found');
const shared=blocks.join('\n\n'),hash=crypto.createHash('sha256').update(shared).digest('hex');
const output=`// Generated by scripts/sync-kasai-replay.cjs. Do not edit by hand.
// Shared browser data/Engine SHA-256: ${hash}
// Literal source only: this module uses no eval, Function, VM or browser APIs.
function createReplayRuntime(){
  const globalThis={};
${shared}
  return globalThis.LT;
}
const LT=createReplayRuntime();
export const RULES_VERSION=LT.KasaiRules.version;
export const MAX_ACTIONS=LT.KasaiRules.maxActions;
export const KASAI_TEAM=LT.KasaiRules.team;
export const normalizeParty=party=>LT.KasaiRules.normalizeParty(party);
export function replayChallenge(party,seed,actions){
  const invalid=reason=>({ok:false,won:false,result:null,turns:0,reason});
  if(!Number.isSafeInteger(seed)||seed<0||seed>0xffffffff)return invalid('Invalid challenge seed');
  if(!Array.isArray(actions)||!actions.length||actions.length>MAX_ACTIONS)return invalid('Invalid action count');
  let normalized;
  try{normalized=normalizeParty(party);}catch(_){return invalid('Invalid challenge party');}
  const engine=new LT.Engine();engine.state.started=true;engine.state.party=normalized;
  engine.state.seen=[...new Set(normalized.map(mon=>mon.species))];engine.state.caught=engine.state.seen.slice();
  if(!engine.startKasaiBattle({id:'server-replay',token:'server-replay-validation',seed,rulesVersion:RULES_VERSION,party:normalized}).ok)return invalid('Challenge could not start');
  for(const input of actions){
    const action=LT.KasaiRules.normalizeAction(input);
    if(!action||engine.battle.result)return invalid('Invalid or trailing action');
    const result=action.type==='replace'?engine.chooseReplacement(action.index):engine.action(action);
    if(!result.ok)return invalid('Illegal battle action');
  }
  const result=engine.battle.result;
  return {ok:true,won:result==='won',result,turns:engine.battle.turn};
}
`;
const target=path.join(root,'server','kasai-replay.mjs');
if(process.argv.includes('--check')){
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output)throw Error('Kasai replay is stale. Run node scripts/sync-kasai-replay.cjs');
  console.log('Kasai replay source matches the shipped browser Engine.');
}else{fs.writeFileSync(target,output);console.log(`Generated Kasai replay (${Buffer.byteLength(output)} bytes).`);}
